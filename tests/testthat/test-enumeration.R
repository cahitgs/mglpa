test_that("class enumeration collects fits and a table", {
  enum <- enumerate_profiles(wm, ind, group = "group", k = 1:2, starts = c(5, 2), seed = 1,
                             verbose = FALSE)
  expect_s3_class(enum, "mglpa_enumeration")
  expect_equal(names(enum$fits), c("1", "2"))
  expect_equal(names(enum$fits[["1"]]), c("1", "2"))
  expect_equal(nrow(enum$table), 4)
  expect_equal(enum$table$npar, c(10, 16, 10, 16))
  expect_equal(enum$table$LL[1], ref_value("enumeration", "ll", group = 1, k = 1), tolerance = 1e-5)
  expect_equal(enum$table$LL[3], ref_value("enumeration", "ll", group = 2, k = 1), tolerance = 1e-5)
  # VLMR / aLMR tests of k versus k - 1 profiles (Mplus TECH11)
  expect_true(all(c("LRT", "VLMR_p", "aLMR_p") %in% names(enum$table)))
  expect_equal(which(names(enum$table) == "LRT"), which(names(enum$table) == "entropy") + 1L)
  expect_true(all(is.na(enum$table$VLMR_p[enum$table$k == 1])))
  expect_true(all(enum$table$VLMR_p[enum$table$k == 2] < 0.001))
  expect_true(all(enum$table$aLMR_p[enum$table$k == 2] < 0.001))
  expect_equal(names(enum$vlmr), c("1 2", "2 2"))
  expect_output(print(enum), "VLMR_p")
  expect_true("aLMR p" %in% names(apa_table(enum)))
  enum0 <- enumerate_profiles(wm1, ind, k = 1:2, starts = c(2, 1), seed = 1, verbose = FALSE, lrt = FALSE)
  expect_false("VLMR_p" %in% names(enum0$table))
  expect_s3_class(elbow_plot(enum), "ggplot")
  expect_s3_class(apa_table(enum), "data.frame")
  expect_output(print(enum), "Group 2")
  f <- enum$fits[["1"]][["2"]]
  expect_s3_class(profile_plot(f), "ggplot")
  expect_s3_class(profile_plot(f, "line"), "ggplot")
  expect_s3_class(profile_plot(f, "radar"), "ggplot")
  tmp <- tempfile(fileext = ".doc")
  write_table_doc(apa_table(enum), tmp, title = "Table 1")
  expect_true(file.exists(tmp))
  expect_true(any(grepl("<table>", readLines(tmp, warn = FALSE), fixed = TRUE)))
})

